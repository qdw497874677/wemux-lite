import { createServer } from 'node:http'
import { once } from 'node:events'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'
import { launchAcceptanceBrowser } from './acceptance-runtime.mjs'
import { observeAcceptanceNavigation } from './acceptance-navigation.mjs'

// Keep the scenario failure first while retaining every cleanup failure for diagnosis.
// Callbacks also allow failure-path tests without launching Chromium.
export async function runWithAbortFixtureCleanup(scenario, cleanups) {
  const errors = []
  let result
  try { result = await scenario() } catch (error) { errors.push(error) }
  for (const cleanup of cleanups) {
    try { await cleanup() } catch (error) { errors.push(error) }
  }
  if (errors.length === 1) throw errors[0]
  if (errors.length > 1) throw new AggregateError(errors, 'Abort fixture failed; scenario/cleanup errors retained in execution order', { cause: errors[0] })
  return result
}

// Request IDs are generated by this isolated page, carried as a same-origin header,
// and persisted instead of real entity IDs, URLs, cookies, headers or response bodies.
export async function runAbortRaceFixture({ evidence = process.env.WEMUX_ABORT_FIXTURE_EVIDENCE ?? '/tmp/wemux-ticket01-abort-fixture/browser', mutation } = {}) {
  const events = [], ids = {}, cancelled = []
  let seq = 0, externalRequests = 0, nonGetRequests = 0, server, browser, pendingNavigation
  const record = value => events.push({ seq: ++seq, hostMs: performance.now(), ...value })
  const wait = async predicate => {
    const until = Date.now() + 8000
    while (!predicate()) {
      if (Date.now() > until) throw Error('Fixture event barrier timed out')
      await new Promise(resolve => setTimeout(resolve, 10))
    }
  }
  const has = (requestId, source, event) => events.some(e => e.requestId === requestId && e.source === source && e.event === event)
  const bundle = await build({ entryPoints: [fileURLToPath(new URL('./abort-race-page.mjs', import.meta.url))], bundle: true, write: false, format: 'iife', platform: 'browser', alias: { '@wemux/web-client': fileURLToPath(new URL('../../../packages/web-client/src/index.ts', import.meta.url)) } })
  const sourceHashes = {}
  for (const path of ['../../web/src/api/client.ts', '../../../packages/web-client/src/cluster-transport.ts', './abort-race-page.mjs']) {
    sourceHashes[path] = createHash('sha256').update(await readFile(new URL(path, import.meta.url))).digest('hex')
  }
  const html = '<!doctype html><link rel="icon" href="data:,"><title>Local abort race fixture</title><script src="/fixture.js"></script>'
  await mkdir(evidence, { recursive: true, mode: 0o700 })
  return runWithAbortFixtureCleanup(async () => {
    server = createServer((request, response) => {
      const path = new URL(request.url, 'http://fixture.invalid').pathname
      if (request.method !== 'GET') { nonGetRequests++; response.writeHead(405).end(); return }
      if (path === '/fixture.js') { response.writeHead(200, { 'Content-Type': 'text/javascript' }).end(bundle.outputFiles[0].text); return }
      if (path === '/next-document') { pendingNavigation = response; record({ source: 'server', event: 'navigation-received' }); return }
      const rawId = request.headers['x-fixture-request-id']
      const requestId = typeof rawId === 'string' && /^fixture-[a-z]+-\d+$/.test(rawId) ? rawId : undefined
      if (!requestId) { response.writeHead(200, { 'Content-Type': 'text/html' }).end(html); return }
      record({ source: 'server', event: 'received', requestId, path })
      response.on('finish', () => record({ source: 'server', event: 'finished', requestId }))
      response.on('close', () => record({ source: 'server', event: 'closed', requestId, ended: response.writableEnded, headersSent: response.headersSent }))
      const headers = (status, contentType) => {
        response.writeHead(status, { 'Content-Type': contentType, 'Cache-Control': 'no-store' }); response.flushHeaders()
        record({ source: 'server', event: 'headers', requestId, status })
      }
      const scenario = requestId.split('-')[1]
      if (scenario === 'drop') { record({ source: 'server', event: 'socket-destroy', requestId }); response.destroy(); return }
      if (scenario === 'http' || scenario === 'private') {
        headers(scenario === 'http' ? 500 : 401, 'application/json'); response.end('{}'); return
      }
      if (scenario === 'scope' && path.endsWith('/events') && path.startsWith('/api/sessions/')) {
        // Deliberately incomplete body: 401 processing happens at headers, before body end.
        headers(401, 'application/json'); response.write('{'); return
      }
      if (['sse', 'scope'].includes(scenario)) { headers(200, 'text/event-stream'); response.write(': connected\n\n'); return }
      // Queries, late read and favicon stay unanswered until the client closes.
    })
    server.listen(0, '127.0.0.1'); await once(server, 'listening')
    const origin = `http://127.0.0.1:${server.address().port}`
    browser = await launchAcceptanceBrowser()
    const context = await browser.newContext({ serviceWorkers: 'block' })
    await context.route(new RegExp(`^(?!${origin.replaceAll('.', '\\.')}(/|$))https?://`), route => { externalRequests++; return route.abort('blockedbyclient') })
    async function pageFor(scenario) {
      const page = await context.newPage()
      await page.exposeFunction('fixtureEvent', record)
      await page.addInitScript(value => { window.fixtureScenario = value }, scenario)
      await page.goto(origin)
      await page.waitForFunction(() => window.fixtureReady)
      const navigation = observeAcceptanceNavigation(page, event => record({ source: 'navigation', ...event }))
      const id = request => request.headers()['x-fixture-request-id']
      page.on('request', request => { if (id(request)) record({ source: 'browser', event: 'request', requestId: id(request), startEpoch: navigation.startEpoch(request) }) })
      page.on('response', response => { if (id(response.request())) record({ source: 'browser', event: 'response', requestId: id(response.request()), status: response.status(), contentType: response.headers()['content-type'] }) })
      page.on('requestfinished', request => { if (id(request)) record({ source: 'browser', event: 'finished', requestId: id(request) }) })
      page.on('requestfailed', request => {
        if (id(request)) navigation.failure(request, evidence => record({ source: 'browser', event: 'failed', requestId: id(request), reason: request.failure()?.errorText, navigation: evidence }))
      })
      return { page, navigation }
    }
    async function started(scenario, count) {
      const requestIds = () => [...new Set(events.filter(e => e.source === 'server' && e.event === 'received' && e.requestId.startsWith(`fixture-${scenario}-`)).map(e => e.requestId))]
      await wait(() => requestIds().length === count)
      return requestIds()
    }
    async function closed(list) {
      for (const id of list) await wait(() => has(id, 'server', 'closed') && has(id, 'browser', 'failed') && has(id, 'document', 'signal-abort'))
      cancelled.push(...list)
    }
    for (const scenario of ['sse', 'scope']) {
      const { page } = await pageFor(scenario)
      await page.evaluate(() => window.fixture.startStreams())
      const streams = await started(scenario, 2)
      for (const id of streams) await wait(() => has(id, 'document', 'fetch-response') && has(id, 'browser', 'response'))
      ids[scenario] = { project: streams.find(id => events.some(e => e.requestId === id && e.path?.startsWith('/api/projects/'))), session: streams.find(id => events.some(e => e.requestId === id && e.path?.startsWith('/api/sessions/'))) }
      if (scenario === 'sse') await page.evaluate(() => window.fixture.stopStreams())
      else {
        await page.evaluate(() => window.fixture.trigger401())
        const all = await started(scenario, 3)
        ids.unauthorized = all.find(id => !streams.includes(id))
        await closed([ids.unauthorized])
      }
      await closed(streams); await page.close()
    }
    {
      const { page } = await pageFor('query')
      await page.evaluate(() => window.fixture.startQueries())
      ids.query = await started('query', 2)
      if (mutation !== 'omit-query-cancel') await page.evaluate(() => window.fixture.routeCleanup())
      await closed(ids.query); await page.close()
    }
    {
      const { page, navigation } = await pageFor('late')
      // Server holds navigation headers so the outgoing document demonstrably remains live.
      await page.evaluate(() => {
        // Arm in the old document: Playwright evaluate during pending goto waits
        // for commit. Assertions require intent < this request < commit.
        setTimeout(() => {
          window.fixture.startRaw('/api/projects/fixture-project/activity')
          setTimeout(() => window.fixture.abortRaw(), 200)
        }, 100)
      })
      const navigating = navigation.navigate('goto', `${origin}/next-document`)
      void navigating.catch(() => {})
      await wait(() => !!pendingNavigation)
      ;[ids.late] = await started('late', 1)
      await wait(() => has(ids.late, 'server', 'closed') && has(ids.late, 'document', 'signal-abort'))
      pendingNavigation.writeHead(200, { 'Content-Type': 'text/html' }).end('<title>Committed document</title>')
      await navigating; await closed([ids.late]); await page.close()
    }
    for (const [scenario, key, path] of [['drop', 'drop', '/api/projects'], ['http', 'http500', '/api/workers'], ['private', 'private401', '/api/workers'], ['favicon', 'favicon', '/favicon.ico?fixture=1']]) {
      const { page } = await pageFor(scenario)
      await page.evaluate(path => window.fixture.startRaw(path), path)
      ;[ids[key]] = await started(scenario, 1)
      if (scenario === 'favicon') { await page.evaluate(() => window.fixture.abortRaw()); await closed([ids[key]]) }
      else await wait(() => has(ids[key], 'browser', scenario === 'drop' ? 'failed' : 'finished'))
      await page.close()
    }
    return { events, ids, cancelled, externalRequests, nonGetRequests }
  }, [
    () => writeFile(`${evidence}/events.json`, JSON.stringify({ scope: 'local fixture/current source only; not deployed release evidence', mutation: mutation ?? null, sourceHashes, ids, cancelled, externalRequests, nonGetRequests, events }, null, 2), { mode: 0o600 }),
    () => browser?.close(),
    async () => {
      if (server) {
        server.closeAllConnections()
        await new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve()))
      }
    },
  ])
}
